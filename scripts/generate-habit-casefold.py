from pathlib import Path
import hashlib,json
root=Path(__file__).resolve().parent.parent
source=root/'contracts/primeiro-marco/unicode/CaseFolding-17.0.0.txt'
raw=source.read_bytes()
mappings={}
for line in raw.decode('utf-8').splitlines():
 row=line.split('#',1)[0].strip()
 if not row: continue
 code,status,values,_=row.split(';')
 if status.strip() in ('C','F'):
  mappings[int(code,16)]=''.join(chr(int(value,16)) for value in values.split())
entries=[json.dumps(str(code))+':'+json.dumps(value,ensure_ascii=True) for code,value in mappings.items()]
body='// Generated by scripts/generate-habit-casefold.py. Unicode License V3 in app/assets/licenses.\n// Unicode 17.0.0 C+F (default full fold); source SHA-256 '+hashlib.sha256(raw).hexdigest()+'\n'
body+='export const caseFold:Readonly<Record<number,string>>={\n'+'\n'.join(' '+','.join(entries[i:i+10])+',' for i in range(0,len(entries),10))+'\n};\n'
(root/'app/src/features/habits/domain/case-fold.ts').write_text(body,encoding='utf-8',newline='\n')
print('Generated',len(mappings),'Unicode full-fold mappings')
