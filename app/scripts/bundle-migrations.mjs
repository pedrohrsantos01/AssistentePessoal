import fs from 'node:fs';
for(const folder of ['drizzle','drizzle-control']) {
const directory=new URL('../'+folder+'/',import.meta.url);
const journal=JSON.parse(fs.readFileSync(new URL('meta/_journal.json',directory),'utf8'));
const migrations=Object.fromEntries(journal.entries.map(entry=>[
  'm'+String(entry.idx).padStart(4,'0'),
  fs.readFileSync(new URL(entry.tag+'.sql',directory),'utf8').trim(),
]));
fs.writeFileSync(new URL('migrations.ts',directory),'// Generated by pnpm db:bundle. Source: numbered SQL files and meta/_journal.json.\nexport default '+JSON.stringify({journal,migrations},null,2)+';\n');

}
